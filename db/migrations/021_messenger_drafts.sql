CREATE TABLE outreach_messenger_drafts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  collection text NOT NULL,
  channel text NOT NULL CHECK (channel IN ('telegram', 'max', 'vk')),
  address text NOT NULL,
  name text NOT NULL,
  role text NOT NULL DEFAULT '',
  company text NOT NULL,
  website text NOT NULL DEFAULT '',
  region text NOT NULL DEFAULT '',
  source_url text NOT NULL,
  fact text NOT NULL DEFAULT '',
  fact_url text NOT NULL DEFAULT '',
  opportunity text NOT NULL DEFAULT '',
  case_url text NOT NULL DEFAULT '',
  case_reason text NOT NULL DEFAULT '',
  partnership boolean NOT NULL DEFAULT false,
  review_reason text NOT NULL DEFAULT '',
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000),
  sent_body text CHECK (char_length(sent_body) BETWEEN 1 AND 4000),
  sent_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((sent_at IS NULL) = (sent_body IS NULL)),
  UNIQUE (collection, channel, address)
);
